const SYMBOLS: ReadonlyMap<string, SdkSymbol> = (() => {
  const map = new Map<string, SdkSymbol>();
  for (const [module, kinds] of Object.entries(TABLE)) {
    for (const [kind, names] of Object.entries(kinds) as [SdkKind, string[]][]) {
      for (const name of names) {
        // A name listed twice (Binding: struct and wrapper) keeps the wrapper meaning.
        if (!map.has(name) || kind === 'property_wrapper') map.set(name, { module, kind });
      }
    }
  }
  return map;
})();

export function sdkSymbol(name: string): SdkSymbol | undefined {
  return SYMBOLS.get(name);
}
